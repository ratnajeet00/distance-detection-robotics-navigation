#!/usr/bin/env python
"""Run optional visualizations on real dataset images only.

The default input is a real BDD100K frame. No images, boxes, or scenes are
generated by this script.

Example:
    python scripts/real_demo.py --source data/bdd/images/train/frame.jpg ^
      --weights runs/detect/runs/train/bdd_finetune/weights/best.pt ^
      --output results/real_bdd_bev.jpg
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.pipeline import DistancePipeline


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--source", required=True,
                    help="path to a real BDD100K or other dataset image")
    ap.add_argument("--weights", required=True)
    ap.add_argument("--output", default="results/real_bdd_bev.jpg")
    ap.add_argument("--backend", choices=("torch", "onnx"), default="torch")
    ap.add_argument("--bev", action="store_true",
                    help="overlay the configured ground-plane BEV")
    args = ap.parse_args()

    source = Path(args.source)
    if not source.is_file():
        raise FileNotFoundError(f"real source image not found: {source}")
    pipeline = DistancePipeline(weights_override=args.weights,
                                backend=args.backend)
    if args.bev:
        pipeline.enable_bev()
    pipeline.run_source(str(source), output=args.output, show=False)
    print(f"[real-demo] input: {source}")
    print(f"[real-demo] output: {args.output}")


if __name__ == "__main__":
    main()
